r"""make_equations.py: step 2b, render flat equations (stage 2 data: sequences of symbols).

PIPELINE  data_collection/: 1 get_fonts -> 2 make_dataset -> 2b make_equations -> 3 data_figures -> 4 hasy
          training/:        5 tune (optional) -> 6 train
          evaluation/:      7 final_test (once, at the end); equation_eval (stage 2)
THIS FILE step 2b (~1 min on CPU)
READS     fonts/, data/meta.json (class ids, from step 2), symbols.CLASSES, fonts_config.FONTS
WRITES    data/equations/<split>/eq_00000.png   one equation per image (black ink on white)
          data/equations/<split>.jsonl          per equation: file, font, tokens, labels, boxes
          data/equations/summary.json           counts, length / class statistics
          figures/equations_macros.tex, figures/fig_equations.{pdf,png}
USED BY   evaluation/segment.py, evaluation/equation_eval.py, the report
RUN       python src/data_collection/make_equations.py [--n-train 2000 --n-val 500 --n-test 500]
------------------------------------------------------------------------------

Proposal, stage 2: "flat equations are generated by rendering sequences of class-set
symbols one at a time (font and spacing varied), keeping each symbol's box and label."

1. Grammar. Instead of random symbol strings, equations come from a small grammar of
   flat (single-line) math: terms joined by binary operators, relations, chains of
   inequalities, function calls f ( x ), brackets, intervals, sets { a , b },
   quantifiers (\forall x \in A , ...), implications, factorials, and a final
   punctuation mark. Every token is one of the 160 classes. No fractions, exponents,
   subscripts or roots (the proposal's "no difficult structure").
2. Rendering. One font per equation, drawn from the split's fonts (train / val / test
   fonts stay disjoint, as for single symbols). Each symbol is drawn at its natural
   size on a shared baseline (Pillow anchor "ls"), so relative size and height are
   kept (x vs X, . vs \cdot). Spacing follows TeX's rules (ordinary 0, binary operator
   4/18 em, relation 5/18 em, after punctuation 3/18 em) with random jitter and a random
   global tightness, so some neighbours touch, as in real documents.
3. Labels. Every symbol is drawn on its own layer too: its ink box (threshold 96 of 255,
   the same as the segmenter) and its class id are stored in reading order.
Everything is seeded.
"""
import argparse, json, os, sys
from pathlib import Path

import numpy as np
from PIL import Image, ImageChops, ImageDraw, ImageFont

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from fonts_config import FONTS
from render import cmap
from symbols import CLASSES, STYLE_PROB_DEFAULT

INK = 96                      # ink threshold (of 255) for boxes; segment.py uses the same
FONT_PX = (40, 56)            # font size range (em in px) per equation
MU = 1 / 18                   # TeX math unit, fraction of the em
MAX_TOKENS, MIN_TOKENS = 20, 3

# ---------------------------------------------------------------- token pools (class labels)
DIGITS = list("0123456789")
LATIN = [chr(c) for c in range(ord("a"), ord("z") + 1)] + [chr(c) for c in range(ord("A"), ord("Z") + 1)]
GREEK = [c["latex"] for c in CLASSES if c["group"] in ("greek_lower", "greek_upper")]
BINOP = ["+"] * 6 + ["-"] * 5 + ["\\cdot"] * 2 + ["\\times"] * 2 + ["/", "\\div", "\\pm", "\\mp",
         "\\ast", "\\circ", "\\cup", "\\cap", "\\wedge", "\\vee"]
REL = ["="] * 8 + ["<", ">", "\\leq", "\\geq"] * 2 + ["\\neq", "\\approx", "\\equiv", "\\sim",
       "\\propto", "\\ll", "\\gg", "\\to", "\\perp"]
SETREL = ["\\in", "\\notin", "\\subset", "\\subseteq", "\\supset", "\\supseteq"]
ARROW = ["\\Rightarrow", "\\Leftarrow", "\\Leftrightarrow", "\\to", "\\leftarrow"]
PUNCT_END = [".", ",", ";", ":"]
SPECIAL = ["\\infty", "\\emptyset"]

# TeX spacing class of every token (ord / bin / rel / punct / open / close)
KIND = {**{t: "bin" for t in BINOP}, **{t: "rel" for t in REL + SETREL + ARROW},
        **{t: "punct" for t in PUNCT_END}, **{t: "open" for t in ["(", "[", "\\{"]},
        **{t: "close" for t in [")", "]", "\\}"]}}
GAP = {("ord", "bin"): 4, ("bin", "ord"): 4, ("ord", "rel"): 5, ("rel", "ord"): 5,
       ("close", "bin"): 4, ("bin", "open"): 4, ("close", "rel"): 5, ("rel", "open"): 5,
       ("punct", "ord"): 3, ("punct", "open"): 3, ("rel", "bin"): 0}


class Grammar:
    """Random flat equations as lists of class labels (a tiny recursive grammar)."""

    def __init__(self, rng):
        self.r = rng

    def pick(self, xs):
        return xs[int(self.r.integers(len(xs)))]

    def var(self):
        return self.pick(LATIN) if self.r.random() < 0.65 else self.pick(GREEK)

    def number(self):
        n = int(self.r.choice([1, 1, 1, 2, 2, 3]))
        first = self.pick(DIGITS[1:]) if n > 1 else self.pick(DIGITS)
        return [first] + [self.pick(DIGITS) for _ in range(n - 1)]

    def atom(self, depth):
        u = self.r.random()
        if u < 0.42:
            return [self.var()]
        if u < 0.60:
            return self.number()
        if u < 0.70:
            return self.number() + [self.var()]                     # 2x
        if u < 0.76:
            return [self.var(), self.var()]                         # ab
        if u < 0.83:
            return [self.pick(["f", "g", "h", "\\phi", "\\psi"]), "("] + self.expr(depth + 1, 1) + [")"]
        if u < 0.91 and depth < 2:
            o, c = self.pick([("(", ")"), ("(", ")"), ("[", "]"), ("\\{", "\\}")])
            return [o] + self.expr(depth + 1) + [c]
        if u < 0.95:
            return ["|"] + self.expr(depth + 1, 1) + ["|"]
        if u < 0.97:
            return [self.pick(["\\partial", "\\nabla"]), self.var()]
        if u < 0.985:
            return [self.var(), "!"]                                # n!
        return [self.pick(SPECIAL)]

    def expr(self, depth=0, max_ops=3):
        out = self.atom(depth)
        for _ in range(int(self.r.integers(0, max_ops + 1))):
            out += [self.pick(BINOP)] + self.atom(depth)
        return out

    def statement(self):
        u = self.r.random()
        if u < 0.45:
            s = self.expr() + [self.pick(REL)] + self.expr()
        elif u < 0.53:                                              # a < x \leq b
            r = self.pick(["<", "\\leq"])
            s = self.expr(1, 1) + [r] + [self.var()] + [self.pick(["<", "\\leq"])] + self.expr(1, 1)
        elif u < 0.63:                                              # f ( x ) = ...
            s = [self.pick(["f", "g", "h", "F", "\\phi"]), "(", self.var(), ")", "="] + self.expr()
        elif u < 0.71:                                              # \forall x \in A , x > 0
            s = [self.pick(["\\forall", "\\exists"]), self.var(), self.pick(SETREL),
                 self.pick(LATIN[26:]), ","] + self.expr(1, 1) + [self.pick(REL)] + self.expr(1, 1)
        elif u < 0.78:                                              # A = \{ a , b , c \}
            items = [self.var() for _ in range(int(self.r.integers(2, 5)))]
            s = [self.pick(LATIN[26:]), "=", "\\{"] + sum(([x, ","] for x in items), [])[:-1] + ["\\}"]
        elif u < 0.84:                                              # x \in [ a , b )
            s = [self.var(), self.pick(SETREL), self.pick(["(", "["]), *self.number(), ",",
                 self.pick([self.var(), "\\infty"]), self.pick([")", "]"])]
        elif u < 0.90:                                              # p \wedge q \Rightarrow r
            s = self.expr(1, 1) + [self.pick(ARROW)] + self.expr(1, 1)
        elif u < 0.94:                                              # \neg ( p \vee q )
            s = ["\\neg", "("] + self.expr(1, 1) + [")", self.pick(REL)] + self.expr(1, 1)
        elif u < 0.97:                                              # A \cup B = \emptyset
            a, b = self.pick(LATIN[26:]), self.pick(LATIN[26:])
            s = [a, self.pick(["\\cup", "\\cap"]), b, self.pick(["=", "\\neq"]), "\\emptyset"]
        else:                                                       # \angle A \perp ...
            s = ["\\angle", self.pick(LATIN[26:]), self.pick(["=", "\\approx"])] + self.number()
        if self.r.random() < 0.15:
            s.append(self.pick(PUNCT_END))
        return s

    def equation(self):
        while True:
            s = self.statement()
            if MIN_TOKENS <= len(s) <= MAX_TOKENS:
                return s


def kind(tok):
    return KIND.get(tok, "ord")


def render_equation(tokens, font_path, px, rng, by_label):
    """Draw tokens left to right on one baseline. Returns (image 'L' ink=255, boxes, ok)."""
    font = ImageFont.truetype(font_path, px)
    have = cmap(font_path)
    italic = rng.random() < 0.8                                     # math italic letters (LaTeX default)
    tight = rng.uniform(0.75, 1.25)
    chars = []
    for t in tokens:
        c = by_label[t]
        st = c["styles"]
        s = ("italic" if italic else "upright") if len(st) > 1 else next(iter(st))
        if st.get(s) not in have:
            s = next((k for k, cp in st.items() if cp in have), None)
            if s is None:
                return None, None, False
        chars.append(chr(st[s]))
    asc, desc = font.getmetrics()
    pad = px // 3
    # x positions: advance width + TeX-like gap (jittered); italic overhang may make glyphs touch
    xs, x, prev = [], pad, None
    for t, ch in zip(tokens, chars):
        if prev is not None:
            x += GAP.get((kind(prev), kind(t)), 0) * MU * px * tight * rng.uniform(0.6, 1.4)
            x += rng.uniform(-0.03, 0.05) * px                      # small extra jitter
        xs.append(x)
        x += font.getlength(ch)
        prev = t
    W, H = int(np.ceil(x + 2 * pad)), int(asc + desc + 2 * pad)
    base = pad + asc
    img = Image.new("L", (W, H), 0)
    boxes = []
    for x0, ch in zip(xs, chars):
        layer = Image.new("L", (W, H), 0)
        ImageDraw.Draw(layer).text((x0, base), ch, font=font, fill=255, anchor="ls")
        ink = np.asarray(layer) > INK
        if not ink.any():
            return None, None, False
        ys_, xs_ = np.where(ink)
        boxes.append([int(xs_.min()), int(ys_.min()), int(xs_.max()) + 1, int(ys_.max()) + 1])
        img = ImageChops.lighter(img, layer)
    return img, boxes, True


def fig_equations(examples, out, n=4):
    """A few generated equations with their ground-truth symbol boxes."""
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.patches import Rectangle
    ex = examples[:n]
    fig, axes = plt.subplots(len(ex), 1, figsize=(6.4, 0.62 * len(ex)))
    for ax, (img, boxes, tokens, fname) in zip(np.atleast_1d(axes), ex):
        ax.imshow(255 - np.asarray(img), cmap="gray", vmin=0, vmax=255)
        for b in boxes:
            ax.add_patch(Rectangle((b[0] - 0.5, b[1] - 0.5), b[2] - b[0], b[3] - b[1], fill=False,
                                   lw=0.5, ec="#c0392b"))
        ax.set_xticks([]); ax.set_yticks([])
        ax.set_ylabel(fname, rotation=0, ha="right", va="center", fontsize=6)
        ax.set_title(" ".join(tokens), fontsize=5.5, loc="left", pad=1, family="monospace")
    fig.tight_layout(pad=0.2, h_pad=0.3)
    for ext in ("pdf", "png"):
        fig.savefig(out / f"fig_equations.{ext}", bbox_inches="tight", pad_inches=0.02, dpi=300)
    plt.close(fig)


def main():
    """Generate the equations of every split, save images + labels + statistics."""
    ap = argparse.ArgumentParser()
    ap.add_argument("--fonts-dir", default="fonts")
    ap.add_argument("--data", default="data")
    ap.add_argument("--figures", default="figures")
    ap.add_argument("--n-train", type=int, default=2000)
    ap.add_argument("--n-val", type=int, default=500)
    ap.add_argument("--n-test", type=int, default=500)
    ap.add_argument("--seed", type=int, default=360)
    a = ap.parse_args()
    data, figs = Path(a.data), Path(a.figures)
    out = data / "equations"; figs.mkdir(parents=True, exist_ok=True)
    meta = json.loads((data / "meta.json").read_text(encoding="utf-8"))
    cid = {c["latex"]: k for k, c in enumerate(meta["classes"])}
    for k, c in enumerate(meta["classes"]):
        for al in c.get("aliases", []):
            cid[al] = k
    by_label = {c["latex"]: c for c in CLASSES}
    fonts = {}
    for name, (pkg, regex, split, note, inner) in FONTS.items():
        p = next((f for f in Path(a.fonts_dir).iterdir() if __import__("re").search(regex, f.name)), None)
        if p is not None:
            fonts.setdefault(split, []).append((name, str(p)))

    summary, examples = {}, []
    for si, (split, n) in enumerate((("train", a.n_train), ("val", a.n_val), ("test", a.n_test))):
        rng = np.random.default_rng([a.seed, 1000 + si])
        g = Grammar(rng)
        (out / split).mkdir(parents=True, exist_ok=True)
        lines, lengths, counts = [], [], np.zeros(len(meta["classes"]), int)
        i = 0
        while i < n:
            tokens = g.equation()
            fname, fpath = fonts[split][int(rng.integers(len(fonts[split])))]
            px = int(rng.integers(FONT_PX[0], FONT_PX[1] + 1))
            img, boxes, ok = render_equation(tokens, fpath, px, rng, by_label)
            if not ok:                                              # font lacks a glyph: redraw
                continue
            file = f"{split}/eq_{i:05d}.png"
            Image.eval(img, lambda v: 255 - v).save(out / file)    # black ink on white, like a page
            labels = [cid[t] for t in tokens]
            lines.append(json.dumps(dict(file=file, font=fname, px=px, tokens=tokens,
                                         labels=labels, boxes=boxes)))
            lengths.append(len(tokens)); np.add.at(counts, labels, 1)
            if split == "val" and len(examples) < 6:
                examples.append((img, boxes, tokens, fname))
            i += 1
        (out / f"{split}.jsonl").write_text("\n".join(lines) + "\n", encoding="utf-8")
        summary[split] = dict(equations=n, symbols=int(sum(lengths)), mean_len=float(np.mean(lengths)),
                              max_len=int(max(lengths)), fonts=[f for f, _ in fonts[split]],
                              classes_used=int((counts > 0).sum()),
                              never_used=[meta["classes"][k]["latex"] for k in np.where(counts == 0)[0]])
        print(f"{split:5s}: {n} equations, {sum(lengths)} symbols, mean length {np.mean(lengths):.1f}, "
              f"{(counts > 0).sum()} classes used")
    (out / "summary.json").write_text(json.dumps(summary, indent=1), encoding="utf-8")
    fig_equations(examples, figs)
    S = lambda v: f"{v:,}".replace(",", "{,}")
    (figs / "equations_macros.tex").write_text(
        "".join(f"\\newcommand{{\\Eq{s.capitalize()}N}}{{{S(summary[s]['equations'])}}}\n"
                f"\\newcommand{{\\Eq{s.capitalize()}Symbols}}{{{S(summary[s]['symbols'])}}}\n"
                for s in summary)
        + f"\\newcommand{{\\EqMeanLen}}{{{summary['train']['mean_len']:.1f}}}\n"
        + f"\\newcommand{{\\EqClassesUsed}}{{{summary['train']['classes_used']}}}\n", encoding="utf-8")
    print(f"wrote {out}/ and {figs}/equations_macros.tex, fig_equations")


if __name__ == "__main__":
    main()
